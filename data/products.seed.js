const makeImages = (slug, title) => {
  const alt = `${title} product image`;

  return [1, 2, 3].map((index) => ({
    url: `https://picsum.photos/seed/${slug}-${index}/1200/900`,
    alt,
  }));
};

const makeSpecs = (specs) => specs.map((spec) => ({ label: spec.label, value: spec.value }));

const makeFeatures = (features) => features.map((feature) => ({ title: feature.title, description: feature.description }));

const createProduct = (product) => {
  const images = makeImages(product.slug, product.name);

  return {
    name: product.name,
    model: product.model,
    slug: product.slug,
    company: product.company,
    brand: product.company,
    description: product.description,
    shortDescription: product.shortDescription || product.description,
    category: product.category,
    subCategories: product.subCategories || [],
    images,
    featuredImage: images[0].url,
    galleryImages: images.map((image) => image.url),
    highlights: product.highlights || [],
    features: makeFeatures(product.features || []),
    specs: makeSpecs(product.specs || []),
    applications: product.applications || [],
    benefits: product.benefits || [],
    downloads: {
      manual: "",
      brochure: "",
      datasheet: "",
    },
    isFeatured: product.isFeatured ?? false,
    isBestSeller: product.isBestSeller ?? false,
    isActive: true,
    tags: product.tags || [],
    sortOrder: product.sortOrder ?? 0,
  };
};

